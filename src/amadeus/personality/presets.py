PERSONAS: dict[str, str] = {
    "amadeus": DEFAULT_PERSONA.strip(),
    "kurisu": KURISU_PERSONA.strip(),
}


def get_persona(name: str) -> str:
    key = name.strip().lower()
    if key not in PERSONAS:
        raise ValueError(f"Неизвестный пресет «{name}». Доступно: {', '.join(PERSONAS)}.")
    return PERSONAS[key]


def write_persona(path: Path, name: str) -> str:
    text = get_persona(name)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text + "\n", encoding="utf-8")
    return text
